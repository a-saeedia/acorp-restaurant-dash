import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useRef,
  useState,
  type ReactNode,
} from 'react';
import { DEMO_NOW_ISO, DEMO_NOW_MS } from '../../simulation/config';
import {
  buildOrderWorkflow,
  buildPurchaseRequestEvent,
  nextOrderSequence,
  resetSimulation,
  applyEvent,
  insertOrder,
} from '../../simulation/engine';
import { buildOrder } from '../../simulation/orders';
import { CUSTOMER_NAMES_FA, TABLE_LABELS_FA } from '../../simulation/catalog';
import type {
  AnalyticsPeriod,
  Order,
  SimulationEvent,
  SimulationState,
} from '../../simulation/types';

/**
 * The demo runs on a compressed clock. One real second advances the simulated
 * business by `TICK_MS * TIME_SCALE` (≈20×); the full order workflow is nine
 * simulated minutes, so a complete run takes about half a minute.
 */
const TICK_MS = 250;
const TIME_SCALE = 20;

export interface SimulationContextValue {
  state: SimulationState;
  clockIso: string;
  playing: boolean;
  speed: number;
  period: AnalyticsPeriod;
  /** Events generated by the demo order, oldest first. */
  events: SimulationEvent[];
  pendingCount: number;
  appliedCount: number;
  recentEvents: SimulationEvent[];
  setPeriod: (period: AnalyticsPeriod) => void;
  setSpeed: (speed: number) => void;
  submitOrder: () => void;
  advance: () => void;
  togglePlay: () => void;
  reset: () => void;
  prepareRequest: (id: string) => void;
  approveRequest: (id: string) => void;
}

const SimulationContext = createContext<SimulationContextValue | null>(null);

/** Demo order factory — same recipe as the video, but timestamped "now". */
function createDemoOrder(state: SimulationState): Order {
  return buildOrder({
    sequence: nextOrderSequence(state),
    channel: 'qr',
    createdAtIso: state.clockIso,
    status: 'received',
    paymentStatus: 'pending',
    customerNameFa: CUSTOMER_NAMES_FA[0] ?? 'سارا محمدی',
    tableFa: TABLE_LABELS_FA[6] ?? 'میز ۷',
    lines: [{ menuItemId: 'menu-classic', quantity: 1, customizationIds: ['c-extra-cheese'] }],
    discountRate: 0,
    cancelReasonFa: null,
  });
}

export function SimulationProvider({ children }: { children: ReactNode }) {
  const [state, setState] = useState<SimulationState>(() => resetSimulation());
  const [events, setEvents] = useState<SimulationEvent[]>([]);
  const [clockMs, setClockMs] = useState(DEMO_NOW_MS);
  const [playing, setPlaying] = useState(false);
  const [speed, setSpeed] = useState(1);
  const [period, setPeriod] = useState<AnalyticsPeriod>('month');

  /* Mirrors for the interval callback, which must not be rebuilt every tick. */
  const stateRef = useRef(state);
  const eventsRef = useRef(events);
  const clockRef = useRef(clockMs);
  stateRef.current = state;
  eventsRef.current = events;
  clockRef.current = clockMs;

  const applyUntil = useCallback((targetMs: number) => {
    let next = stateRef.current;
    const due = eventsRef.current
      .filter((event) => event.atMs <= targetMs && !next.processed[event.id])
      .sort((a, b) => a.atMs - b.atMs);

    for (const event of due) next = applyEvent(next, event);

    stateRef.current = next;
    clockRef.current = targetMs;
    setState(next);
    setClockMs(targetMs);

    const remaining = eventsRef.current.some((event) => !next.processed[event.id]);
    if (!remaining) setPlaying(false);
  }, []);

  useEffect(() => {
    if (!playing) return;
    const timer = window.setInterval(() => {
      const next = clockRef.current + TICK_MS * TIME_SCALE * speed;
      applyUntil(next);
    }, TICK_MS);
    return () => window.clearInterval(timer);
  }, [playing, speed, applyUntil]);

  const submitOrder = useCallback(() => {
    const order = createDemoOrder(stateRef.current);
    const startMs = Math.max(clockRef.current, Date.parse(order.createdAtIso));
    const workflow = buildOrderWorkflow(order.id, startMs);

    const nextState = insertOrder(stateRef.current, order);
    stateRef.current = nextState;
    setState(nextState);
    setEvents((previous) => [...previous, ...workflow]);
    eventsRef.current = [...eventsRef.current, ...workflow];
    setClockMs(startMs);
    clockRef.current = startMs;
    setPlaying(true);
  }, []);

  const advance = useCallback(() => {
    let next = stateRef.current;
    const pending = eventsRef.current
      .filter((event) => !next.processed[event.id])
      .sort((a, b) => a.atMs - b.atMs);

    const event = pending[0];
    if (!event) {
      setPlaying(false);
      return;
    }

    next = applyEvent(next, event);
    stateRef.current = next;
    clockRef.current = Math.max(clockRef.current, event.atMs);
    setState(next);
    setClockMs(clockRef.current);
  }, []);

  const togglePlay = useCallback(() => {
    setPlaying((current) => {
      if (!current) {
        const hasPending = eventsRef.current.some((event) => !stateRef.current.processed[event.id]);
        return hasPending;
      }
      return false;
    });
  }, []);

  const reset = useCallback(() => {
    const fresh = resetSimulation();
    stateRef.current = fresh;
    eventsRef.current = [];
    clockRef.current = DEMO_NOW_MS;
    setState(fresh);
    setEvents([]);
    setClockMs(DEMO_NOW_MS);
    setPlaying(false);
  }, []);

  const mutateRequest = useCallback(
    (id: string, type: 'PURCHASE_REQUEST_PREPARED' | 'PURCHASE_REQUEST_APPROVED') => {
      const request = stateRef.current.purchaseRequests.find((item) => item.id === id);
      if (!request) return;
      const event = buildPurchaseRequestEvent(request, type, clockRef.current + 1000);
      const next = applyEvent(stateRef.current, event);
      stateRef.current = next;
      setState(next);
    },
    [],
  );

  const prepareRequest = useCallback(
    (id: string) => mutateRequest(id, 'PURCHASE_REQUEST_PREPARED'),
    [mutateRequest],
  );
  const approveRequest = useCallback(
    (id: string) => mutateRequest(id, 'PURCHASE_REQUEST_APPROVED'),
    [mutateRequest],
  );

  const pendingCount = useMemo(
    () => events.filter((event) => !state.processed[event.id]).length,
    [events, state.processed],
  );

  const appliedCount = useMemo(
    () => events.filter((event) => Boolean(state.processed[event.id])).length,
    [events, state.processed],
  );

  const recentEvents = useMemo(
    () =>
      events
        .filter((event) => Boolean(state.processed[event.id]))
        .sort((a, b) => b.atMs - a.atMs),
    [events, state.processed],
  );

  const value = useMemo<SimulationContextValue>(
    () => ({
      state,
      clockIso: new Date(clockMs).toISOString(),
      playing,
      speed,
      period,
      events,
      pendingCount,
      appliedCount,
      recentEvents,
      setPeriod,
      setSpeed,
      submitOrder,
      advance,
      togglePlay,
      reset,
      prepareRequest,
      approveRequest,
    }),
    [
      state,
      clockMs,
      playing,
      speed,
      period,
      events,
      pendingCount,
      appliedCount,
      recentEvents,
      submitOrder,
      advance,
      togglePlay,
      reset,
      prepareRequest,
      approveRequest,
    ],
  );

  return <SimulationContext.Provider value={value}>{children}</SimulationContext.Provider>;
}

export function useSimulation(): SimulationContextValue {
  const context = useContext(SimulationContext);
  if (!context) throw new Error('useSimulation must be used inside <SimulationProvider>');
  return context;
}

/** Fixed demo start, exported so the shell can render the seed label. */
export const DEMO_START_ISO = DEMO_NOW_ISO;
